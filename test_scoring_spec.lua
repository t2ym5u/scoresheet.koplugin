-- Scoring of the score sheets: Tarot against the worked examples of the
-- FFT rules ("La marque en donnes libres"), Belote/Coinche hands, the word
-- game's leftover tiles, rummy elimination and the sheet bookkeeping.
local DIR = debug.getinfo(1, "S").source:sub(2):match("(.*[/\\])") or "./"
package.path = DIR .. "?.lua;" .. package.path

local Tarot  = require("tarot")
local Belote = require("belote")
local Sheet  = require("sheet")

local function sum(t)
    local s = 0
    for _i, v in ipairs(t) do s = s + v end
    return s
end

describe("Tarot", function()
    it("FFT example 1: garde, poignée, petit au bout, 49 with 2 oudlers", function()
        local d = { taker = 1, contract = "garde", oudlers = 2, points = 49,
                    petit = "attack", poignee = "simple" }
        local deltas, det = Tarot.score(d, 4)
        assert.are.equal(106, det.unit)
        assert.are.same({ 318, -106, -106, -106 }, deltas)
    end)
    it("FFT example 2: garde sans made by 4, petit au bout lost", function()
        local d = { taker = 2, contract = "garde_sans", oudlers = 1, points = 55,
                    petit = "defense" }
        local deltas = Tarot.score(d, 4)
        assert.are.same({ -76, 228, -76, -76 }, deltas)
    end)
    it("FFT example 3: prise failed by 7, poignée, petit au bout won", function()
        local d = { taker = 3, contract = "petite", oudlers = 2, points = 34,
                    petit = "attack", poignee = "simple" }
        local deltas = Tarot.score(d, 4)
        assert.are.same({ 42, 42, -126, 42 }, deltas)
    end)
    it("counts a poignée from each side, both for the deal's winner", function()
        local base = Tarot.score({ taker = 1, contract = "garde", oudlers = 2, points = 49 }, 4)
        local both = Tarot.score({ taker = 1, contract = "garde", oudlers = 2, points = 49,
                                   poignee = "simple", poignee_def = "double" }, 4)
        assert.are.equal(base[1] + 3 * (20 + 30), both[1])
        assert.are.equal(base[2] - (20 + 30), both[2])
    end)

    it("FFT example 4: garde made by 11, defence showed a poignée", function()
        local d = { taker = 4, contract = "garde", oudlers = 0, points = 67, poignee = "simple" }
        local deltas = Tarot.score(d, 4)
        assert.are.same({ -92, -92, -92, 276 }, deltas)
    end)
    it("FFT example 5: announced chelem on a garde", function()
        local d = { taker = 1, contract = "garde", oudlers = 2, points = 87,
                    petit = "attack", poignee = "simple", chelem = "announced" }
        local deltas = Tarot.score(d, 4)
        assert.are.same({ 1746, -582, -582, -582 }, deltas)
    end)
    it("a contract exactly made scores 25", function()
        local deltas = Tarot.score({ taker = 1, contract = "petite", oudlers = 3, points = 36 }, 4)
        assert.are.same({ 75, -25, -25, -25 }, deltas)
    end)
    it("garde contre multiplies by 6", function()
        local deltas = Tarot.score({ taker = 1, contract = "garde_contre", oudlers = 3, points = 46 }, 4)
        assert.are.same({ 630, -210, -210, -210 }, deltas)
    end)
    it("half points go to the winning side (FFT 3 and 5 players)", function()
        assert.are.equal(40, Tarot.roundPoints(40.5, 41))
        assert.are.equal(42, Tarot.roundPoints(41.5, 41))
        local _d, det = Tarot.score({ taker = 1, contract = "petite", oudlers = 2, points = 40.5 }, 3)
        assert.are.equal(-26, det.unit)
        local _d2, det2 = Tarot.score({ taker = 1, contract = "petite", oudlers = 2, points = 41.5 }, 3)
        assert.are.equal(26, det2.unit)
    end)
    it("3 players: the taker scores twice the deal", function()
        local deltas = Tarot.score({ taker = 2, contract = "garde", oudlers = 2, points = 51 }, 3)
        assert.are.same({ -70, 140, -70 }, deltas)
    end)
    it("5 players: taker 2/3, partner 1/3", function()
        local deltas = Tarot.score({ taker = 1, partner = 4, contract = "garde",
                                     oudlers = 1, points = 61 }, 5)
        -- (25 + 10) x 2 = 70 per defender
        assert.are.same({ 140, -70, -70, 70, -70 }, deltas)
        assert.are.equal(0, sum(deltas))
    end)
    it("5 players: a taker who called himself plays alone (4x)", function()
        local deltas = Tarot.score({ taker = 3, partner = 3, contract = "petite",
                                     oudlers = 1, points = 41 }, 5)
        assert.are.same({ 35, 35, -140, 35, 35 }, deltas)
    end)
    it("chelem failed and defence chelem cost 200", function()
        local _a, det = Tarot.score({ taker = 1, contract = "garde", oudlers = 3, points = 80,
                                       chelem = "failed" }, 4)
        assert.are.equal((25 + 44) * 2 - 200, det.unit)
        local _b, det2 = Tarot.score({ taker = 1, contract = "petite", oudlers = 0, points = 0,
                                        chelem = "defense" }, 4)
        assert.are.equal(-(25 + 56) - 200, det2.unit)
        local _c, det3 = Tarot.score({ taker = 1, contract = "petite", oudlers = 3, points = 91,
                                        chelem = "unannounced" }, 4)
        assert.are.equal(25 + 55 + 200, det3.unit)
    end)
    it("every deal is zero-sum", function()
        for n = 3, 5 do
            for _i, c in ipairs(Tarot.CONTRACTS) do
                for o = 0, 3 do
                    local deltas = Tarot.score({ taker = 1, partner = 2, contract = c, oudlers = o,
                                                 points = 45.5, petit = "defense",
                                                 poignee = "double" }, n)
                    assert.are.equal(0, sum(deltas))
                end
            end
        end
    end)
    it("validates a deal", function()
        assert.is_true(Tarot.isValid({ taker = 1, contract = "garde", oudlers = 2, points = 50 }, 4))
        assert.is_false(Tarot.isValid({ taker = 1, contract = "garde", oudlers = 2, points = 92 }, 4))
        assert.is_false(Tarot.isValid({ contract = "garde", oudlers = 2, points = 50 }, 4))
        assert.is_false(Tarot.isValid({ taker = 1, contract = "x", oudlers = 2, points = 50 }, 4))
    end)
end)

describe("Belote", function()
    it("made: each team scores its points", function()
        local d, det = Belote.classic({ taker = 1, points = 97 })
        assert.is_true(det.made)
        assert.are.same({ 97, 65 }, d)
    end)
    it("belote-rebelote adds 20 and counts to make the contract", function()
        -- 75 + 20 = 95 against 87: made
        local d, det = Belote.classic({ taker = 2, points = 75, belote = 2 })
        assert.is_true(det.made)
        assert.are.same({ 87, 95 }, d)
    end)
    it("dedans: the defence takes 162, belote stays with its holder", function()
        local d, det = Belote.classic({ taker = 1, points = 70, belote = 1 })
        -- 70 + 20 = 90 against 92: failed
        assert.is_false(det.made)
        assert.are.same({ 20, 162 }, d)
        local d2 = Belote.classic({ taker = 1, points = 60, belote = 2 })
        assert.are.same({ 0, 182 }, d2)
    end)
    it("capot scores 252", function()
        assert.are.same({ 252, 0 }, (Belote.classic({ taker = 1, capot = "taker" })))
        assert.are.same({ 272, 0 }, (Belote.classic({ taker = 1, capot = "taker", belote = 1 })))
        assert.are.same({ 0, 252 }, (Belote.classic({ taker = 1, capot = "defense" })))
    end)
    it("litige: the taker's 81 go to the next hand's winner", function()
        local d, det = Belote.classic({ taker = 1, points = 81 })
        assert.is_true(det.litige)
        assert.are.same({ 0, 81 }, d)
        assert.are.equal(81, det.carry)
        local d2, det2 = Belote.classic({ taker = 2, points = 100 }, det.carry)
        assert.are.same({ 62, 181 }, d2)
        assert.are.equal(0, det2.carry)
    end)
end)

describe("Coinche", function()
    it("made without coinche: bid + points made", function()
        local d, det = Belote.coinche({ taker = 1, bid = 100, points = 110 })
        assert.is_true(det.made)
        assert.are.same({ 210, 52 }, d)
    end)
    it("failed: the defence scores 160 + bid", function()
        local d, det = Belote.coinche({ taker = 1, bid = 120, points = 110 })
        assert.is_false(det.made)
        assert.are.same({ 0, 280 }, d)
    end)
    it("belote counts towards the bid and is always kept", function()
        local d = Belote.coinche({ taker = 2, bid = 100, points = 85, belote = 2 })
        assert.are.same({ 77, 205 }, d)
        local d2 = Belote.coinche({ taker = 2, bid = 120, points = 85, belote = 1 })
        assert.are.same({ 300, 0 }, d2)
    end)
    it("coinche doubles and surcoinche quadruples", function()
        assert.are.same({ 360, 0 }, (Belote.coinche({ taker = 1, bid = 100, points = 120, coinche = "coinche" })))
        assert.are.same({ 0, 560 }, (Belote.coinche({ taker = 1, bid = 100, points = 90, coinche = "surcoinche" })))
    end)
    it("an 80 bid still needs 82 to beat the defence", function()
        local _d, det = Belote.coinche({ taker = 1, bid = 80, points = 81 })
        assert.is_false(det.made)
    end)
    it("a capot bid needs every trick", function()
        assert.are.same({ 500, 0 }, (Belote.coinche({ taker = 1, bid = 250, capot = "taker" })))
        assert.are.same({ 0, 410 }, (Belote.coinche({ taker = 1, bid = 250, points = 150 })))
    end)
end)

describe("Sheet", function()
    it("keeps totals, running totals and undo", function()
        local s = Sheet.new("tarot", { "A", "B", "C", "D" })
        Sheet.addRound(s, { 318, -106, -106, -106 })
        Sheet.addRound(s, { -76, 228, -76, -76 })
        assert.are.same({ 242, 122, -182, -182 }, Sheet.totals(s))
        assert.are.same({ 318, -106, -106, -106 }, Sheet.running(s)[1])
        assert.are.same({ 1 }, (Sheet.leaders(s)))
        Sheet.undo(s)
        assert.are.same({ 318, -106, -106, -106 }, Sheet.totals(s))
    end)
    it("belote ends at the target, highest wins", function()
        local s = Sheet.new("belote", { "Us", "Them" }, { target = 300 })
        Sheet.addRound(s, { 162, 0 })
        assert.is_false(Sheet.isOver(s))
        Sheet.addRound(s, { 150, 12 })
        assert.is_true(Sheet.isOver(s))
        assert.are.same({ 1 }, (Sheet.leaders(s)))
    end)
    it("belote carry follows the last hand and comes back on undo", function()
        local s = Sheet.new("belote", { "Us", "Them" })
        Sheet.addRound(s, { 0, 81 }, { carry = 81 })
        assert.are.equal(81, Sheet.carry(s))
        Sheet.addRound(s, { 181, 62 }, { carry = 0 })
        assert.are.equal(0, Sheet.carry(s))
        Sheet.undo(s)
        assert.are.equal(81, Sheet.carry(s))
    end)
    it("rummy: over the threshold is out, the last one standing wins", function()
        local s = Sheet.new("rummy", { "A", "B", "C" }, { threshold = 100 })
        Sheet.addRound(s, { 0, 60, 40 })
        Sheet.addRound(s, { 30, 0, 60 })
        assert.are.same({ 1, 2, 3 }, Sheet.active(s))   -- C has 100: not over yet
        assert.is_false(Sheet.isOver(s))
        Sheet.addRound(s, { 20, 45, 0 })                -- B 105 out
        assert.is_true(Sheet.isEliminated(s, 2))
        assert.are.same({ 1, 3 }, Sheet.active(s))
        assert.are.same({ 1 }, (Sheet.leaders(s)))      -- lowest of the players still in
        Sheet.addRound(s, { 0, 0, 5 })                  -- C 105 out
        assert.is_true(Sheet.isOver(s))
        local rank = Sheet.ranking(s)
        assert.are.equal(1, rank[1].index)
        assert.is_true(rank[3].out)
    end)
    it("rummy threshold is editable", function()
        local s = Sheet.new("rummy", { "A", "B" }, { threshold = 50 })
        Sheet.addRound(s, { 51, 0 })
        assert.is_true(Sheet.isOver(s))
    end)
    it("free sheet: optional target, lowest or highest wins", function()
        local s = Sheet.new("free", { "A", "B" })
        Sheet.addRound(s, { 500, -20 })
        assert.is_false(Sheet.isOver(s))
        assert.are.same({ 1 }, (Sheet.leaders(s)))
        s.opts.low = true
        assert.are.same({ 2 }, (Sheet.leaders(s)))
        s.opts.target = 400
        assert.is_true(Sheet.isOver(s))
    end)
    it("word game: turns rotate, rows pack one turn per player", function()
        local s = Sheet.new("words", { "A", "B", "C" })
        assert.are.equal(1, Sheet.nextPlayer(s))
        Sheet.addRound(s, { 12 }, { player = 1 })
        Sheet.addRound(s, { nil, 30 }, { player = 2 })
        assert.are.equal(3, Sheet.nextPlayer(s))
        Sheet.addRound(s, { nil, nil, 0 }, { player = 3 })
        Sheet.addRound(s, { 64 }, { player = 1 })
        local rows = Sheet.rows(s)
        assert.are.equal(2, #rows)
        assert.are.same({ 12, 30, 0 }, rows[1].cells)
        assert.are.equal(64, rows[2].cells[1])
        assert.is_nil(rows[2].cells[2])
        assert.are.same({ 76, 30, 0 }, Sheet.totals(s))
    end)
    it("word game: leftover tiles are deducted, the one who went out gains them", function()
        assert.are.same({ 9, -4, -5 }, Sheet.leftoverDeltas({ 0, 4, 5 }))
        assert.are.same({ -2, -4, -5 }, Sheet.leftoverDeltas({ 2, 4, 5 }))
        assert.are.same({ 0, 0 }, Sheet.leftoverDeltas({ 0, 0 }))
        local s = Sheet.new("words", { "A", "B" })
        Sheet.addRound(s, { 20 }, { player = 1 })
        Sheet.addRound(s, Sheet.leftoverDeltas({ 0, 7 }), { final = true })
        s.finished = true
        assert.is_true(Sheet.isOver(s))
        Sheet.undo(s)
        assert.is_false(s.finished)
    end)
    it("restores a saved sheet and rejects broken ones", function()
        local s = Sheet.new("tarot", { "A", "B", "C" })
        Sheet.addRound(s, { 2, -1, -1 })
        assert.is_not_nil(Sheet.restore(Sheet.copy(s)))
        assert.is_nil(Sheet.restore({ kind = "tarot", names = { "A" }, rounds = {} }))
        assert.is_nil(Sheet.restore({ kind = "nope", names = { "A", "B" }, rounds = {} }))
        assert.is_nil(Sheet.restore("x"))
    end)
end)
